CREATE TABLE IF NOT EXISTS race_scores (
 id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 nickname VARCHAR(24) NOT NULL,
 level INTEGER NOT NULL CHECK(level BETWEEN 1 AND 20),
 points INTEGER NOT NULL CHECK(points BETWEEN 0 AND 200000),
 finish_ms INTEGER NOT NULL CHECK(finish_ms BETWEEN 15000 AND 3600000),
 car VARCHAR(32) NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS race_scores_top_idx ON race_scores (points DESC, finish_ms ASC);
